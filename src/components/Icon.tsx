export type IconName = keyof typeof grids;

/** One path of 1×1 runs per row: compact and crisp at any integer scale. */
function toPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return d;
}

const paths = Object.fromEntries(Object.entries(grids).map(([k, rows]) => [k, toPath(rows)])) as Record<IconName, string>;

/** `filled` is kept for API compatibility; pixel icons are always solid. */
export function Icon({ name, label }: { name: IconName; label?: string; filled?: boolean }) {
  return (
    <svg
      className="pm-icon"
      viewBox="0 0 12 12"
      fill="currentColor"
      shapeRendering="crispEdges"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      <path d={paths[name]} />
    </svg>
  );
}
