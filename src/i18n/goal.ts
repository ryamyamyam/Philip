export type GoalKey = keyof typeof goalStrings;

export function tg(key: GoalKey, vars?: Vars): string {
  const s: string = goalStrings[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, n: string) => (n in vars ? String(vars[n]) : m)) : s;
}
