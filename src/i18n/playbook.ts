export type PlaybookKey = keyof typeof playbookStrings;

export function tp(key: PlaybookKey, vars?: Vars): string {
  const s: string = playbookStrings[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, n: string) => (n in vars ? String(vars[n]) : m)) : s;
}
